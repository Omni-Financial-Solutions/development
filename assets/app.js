/* ---------- (a) View switching ---------- */
const VIEWS = ["marketing","dashboard","terminal","checkout"];
const glider = $(".vt-glider");
function moveGlider(btn){
  if(!btn || !glider) return;
  glider.style.left  = btn.offsetLeft + "px";
  glider.style.width = btn.offsetWidth + "px";
}
function setView(name, pushHash = true){
  if(!VIEWS.includes(name)) name = "marketing";
  $$(".view").forEach(v => v.classList.toggle("active", v.id === "view-" + name));
  let activeBtn = null;
  $$(".vt-btn").forEach(b => { const on = b.dataset.view === name; b.classList.toggle("active", on); if(on) activeBtn = b; });
  moveGlider(activeBtn);
  if(pushHash && location.hash !== "#" + name){
    history.replaceState(null, "", "#" + name);
  }
  window.scrollTo({top:0});
}
$$(".vt-btn").forEach(b => b.addEventListener("click", () => setView(b.dataset.view)));
$$("[data-view-link]").forEach(el => el.addEventListener("click", e => {
  e.preventDefault();
  setView(el.dataset.viewLink);
}));
/* In-marketing anchors: if the hash names a marketing section, stay in marketing and scroll. */
function routeFromHash(){
  const h = location.hash.replace("#","");
  if(VIEWS.includes(h)){ setView(h, false); return; }
  if(h && document.getElementById(h) && $("#view-marketing").contains(document.getElementById(h))){
    setView("marketing", false);
    requestAnimationFrame(() => document.getElementById(h).scrollIntoView({behavior:"smooth"}));
  }
}
window.addEventListener("hashchange", routeFromHash);
window.addEventListener("resize", () => moveGlider($(".vt-btn.active")));
routeFromHash();
requestAnimationFrame(() => moveGlider($(".vt-btn.active")));

/* ---------- (b) QR generation ---------- */
function qrPattern(seedStr){
  /* deterministic PRNG from a string seed */
  let seed = 2166136261;
  for(const ch of seedStr){ seed ^= ch.charCodeAt(0); seed = Math.imul(seed, 16777619); }
  const rand = () => { seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5; return ((seed >>> 0) % 1000) / 1000; };
  const N = 21, grid = Array.from({length:N}, () => Array(N).fill(0));
  const finder = (x0,y0) => {
    for(let y=0;y<7;y++) for(let x=0;x<7;x++){
      const edge = x===0||x===6||y===0||y===6, core = x>=2&&x<=4&&y>=2&&y<=4;
      grid[y0+y][x0+x] = (edge||core) ? 1 : 0;
    }
  };
  for(let y=0;y<N;y++) for(let x=0;x<N;x++) grid[y][x] = rand() > 0.52 ? 1 : 0;
  finder(0,0); finder(N-7,0); finder(0,N-7);
  /* clear centre for the mint dot */
  for(let y=9;y<12;y++) for(let x=9;x<12;x++) grid[y][x] = 0;
  return grid;
}
$$("[data-qr]").forEach((el, idx) => {
  const size = parseInt(el.dataset.qr, 10) || 80;
  el.style.width = size + "px"; el.style.height = size + "px";
  el.style.display = "grid";
  el.style.gridTemplateColumns = "repeat(21, 1fr)";
  el.style.gridTemplateRows = "repeat(21, 1fr)";
  const grid = qrPattern("omni-renpay-" + idx + "-" + size);
  const frag = document.createDocumentFragment();
  grid.flat().forEach(v => {
    const c = document.createElement("span");
    c.className = "qr-cell" + (v ? " on" : "");
    frag.appendChild(c);
  });
  el.appendChild(frag);
  const core = document.createElement("span");
  core.className = "qr-core"; core.innerHTML = "<i></i>";
  el.appendChild(core);
});


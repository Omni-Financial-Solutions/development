const cart = new Map(); /* id -> qty */
const posItems = $("#pos-items");
posItems.innerHTML = ITEMS.map(i =>
  `<button class="pos-item" data-item="${i.id}"><span class="pos-tile" style="background:${i.color}">${i.tile}</span><strong>${i.name}</strong><small>${money(i.price)}</small></button>`).join("");
$$(".pos-item", posItems).forEach(b => b.addEventListener("click", () => {
  const id = b.dataset.item;
  cart.set(id, (cart.get(id) || 0) + 1);
  renderCart();
}));
function cartTotals(){
  let sub = 0;
  cart.forEach((qty,id) => { const it = ITEMS.find(i => i.id === id); sub += it.price * qty; });
  const tax = sub * 0.13;
  return { sub, tax, total: sub + tax };
}
function renderCart(){
  const lines = $("#cart-lines");
  if(cart.size === 0){
    lines.innerHTML = `<p class="cart-empty">Tap an item to start a sale.</p>`;
  } else {
    lines.innerHTML = [...cart.entries()].map(([id,qty]) => {
      const it = ITEMS.find(i => i.id === id);
      return `<div class="cart-line"><span class="cl-name">${it.name}<small>${money(it.price)} each</small></span>
        <span class="qty"><button data-qty="${id}|-1" aria-label="Remove one">−</button><b>${qty}</b><button data-qty="${id}|1" aria-label="Add one">+</button></span>
        <span class="cl-amt">${money(it.price * qty)}</span></div>`;
    }).join("");
    $$("[data-qty]", lines).forEach(b => b.addEventListener("click", () => {
      const [id, d] = b.dataset.qty.split("|");
      const q = (cart.get(id) || 0) + parseInt(d, 10);
      if(q <= 0) cart.delete(id); else cart.set(id, q);
      renderCart();
    }));
  }
  const t = cartTotals();
  $("#ct-sub").textContent = money(t.sub);
  $("#ct-tax").textContent = money(t.tax);
  $("#ct-total").textContent = money(t.total);
  $("#cust-amount").textContent = money(t.total);
}
$("#cart-clear").addEventListener("click", () => { cart.clear(); renderCart(); });

function showPayState(which){
  ["idle","processing","done"].forEach(s => { const el = $("#pay-state-" + s); if(el) el.hidden = s !== which; });
}
let lastPayment = { method:"RenPay", total:0 };
function startPayment(method){
  if(cartTotals().total <= 0){
    /* preseed a demo sale (the $48.50 café basket used across the site) */
    cart.clear();
    cart.set("beans", 1); cart.set("latte", 1); cart.set("croissant", 1);
    renderCart();
  }
  const t = cartTotals();
  lastPayment = { method, total: t.total };
  const title = $("#processing-title"), sub = $("#processing-sub");
  if(method === "RenPay"){
    title.textContent = "Waiting for RenPay…";
    sub.textContent = "Confirm in your RenPay app. Alfie is verifying the payment inside Renda, no card rails involved.";
  } else {
    title.textContent = "Processing card…";
    sub.textContent = "Alfie is screening this card payment while the terminal talks to your bank.";
  }
  showPayState("processing");
  setTimeout(() => {
    $("#done-sub").textContent = (method === "RenPay" ? "RenPay" : "Card") + " · Paid in full · " + money(t.total);
    $("#receipt-lines").innerHTML =
      [...cart.entries()].map(([id,qty]) => {
        const it = ITEMS.find(i => i.id === id);
        return `<div><span>${it.name} × ${qty}</span><strong>${money(it.price * qty)}</strong></div>`;
      }).join("") +
      `<div><span>HST (13%)</span><strong>${money(t.tax)}</strong></div>` +
      `<div class="grand"><span>Total</span><strong>${money(t.total)}</strong></div>`;
    showPayState("done");
  }, 1600);
}
$("#btn-renpay").addEventListener("click", () => startPayment("RenPay"));
$("#btn-card").addEventListener("click", () => startPayment("Card"));
$("#btn-new-sale").addEventListener("click", () => { cart.clear(); renderCart(); showPayState("idle"); });
renderCart();

